import assert from 'node:assert/strict';
import {mkdtemp, mkdir, readFile, rm, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {tmpdir} from 'node:os';
import {chromium, expect} from '@playwright/test';
import {ensureBrowser} from '@remotion/renderer';
import {createServer} from 'vite';
import {createApp} from '../apps/api/app';
import fixtures from '../tests/fixtures/v1-projects.json';
import {parseProject} from '../packages/project-model/model';

const root = await mkdtemp(path.join(tmpdir(), 'lyrics-track-browser-'));
const base = 'http://127.0.0.1:5174';
const api = await createApp({root, mediaOrigin: base});
const web = await createServer({server: {port: 5174, strictPort: true, proxy: {'/api': 'http://127.0.0.1:3002'}}});
const installed = await ensureBrowser(); assert('path' in installed);
const browser = await chromium.launch({executablePath: installed.path});
try {
  const legacy = parseProject(fixtures[1]), file = path.join(root, legacy.id, 'project.json'), original = JSON.stringify(legacy);
  await mkdir(path.join(root, legacy.id, 'assets'), {recursive: true}); await writeFile(file, original);
  await api.app.listen({host: '127.0.0.1', port: 3002}); await web.listen();
  const page = await browser.newPage({viewport: {width: 1560, height: 1200}});
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base); await page.getByRole('button', {name: `${legacy.name} Open`, exact: true}).click();
  await expect(page.locator('.track.lyric .timeline-clip')).toHaveCount(2);
  assert.equal(await readFile(file, 'utf8'), original, 'Opening V1 must not rewrite its JSON');
  const lane = page.locator('.track.lyric .track-lane'); await lane.scrollIntoViewIfNeeded();
  const bounds = await lane.boundingBox(); assert(bounds);
  await page.mouse.move(bounds.x + 1, bounds.y + 1); await page.mouse.down();
  await page.mouse.move(bounds.x + 310, bounds.y + 55, {steps: 6}); await page.mouse.up();
  await expect(page.getByRole('heading', {name: '2 selected clips', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Group', exact: true}).click();
  await page.locator('.track.lyric .timeline-clip').first().click();
  await expect(page.getByRole('heading', {name: '2 selected clips', exact: true})).toBeVisible();
  const move = page.getByLabel('Move selection by (s)', {exact: true});
  await move.fill('1'); await move.press('Tab');
  await expect(page.getByLabel('Line start (s)', {exact: true})).toHaveValue('2');
  await page.getByRole('button', {name: 'Lock Lyrics', exact: true}).click();
  await move.fill('1'); await move.press('Tab');
  await expect(page.getByRole('alert')).toContainText('Unlock');
  await expect(page.getByLabel('Line start (s)', {exact: true})).toHaveValue('2');
  await page.getByRole('button', {name: 'Dismiss error', exact: true}).click();
  await page.getByRole('button', {name: 'Unlock Lyrics', exact: true}).click();
  await page.getByRole('button', {name: 'Copy', exact: true}).click();
  await page.locator('.ruler').click({position: {x: 360, y: 10}});
  await page.getByRole('button', {name: 'Paste', exact: true}).click();
  await expect(page.locator('.track.lyric .timeline-clip')).toHaveCount(4);
  await page.getByRole('button', {name: 'Undo', exact: true}).click(); await expect(page.locator('.track.lyric .timeline-clip')).toHaveCount(2);
  await page.getByRole('button', {name: 'Redo', exact: true}).click(); await expect(page.locator('.track.lyric .timeline-clip')).toHaveCount(4);
  await page.locator('.track.lyric .timeline-clip').nth(2).click();
  await page.getByRole('button', {name: 'Ripple delete', exact: true}).click(); await expect(page.locator('.track.lyric .timeline-clip')).toHaveCount(2);
  await page.locator('.track.lyric .timeline-clip').first().click(); await page.getByRole('button', {name: 'Ungroup', exact: true}).click();
  await page.locator('.track.lyric .timeline-clip').first().click(); await page.getByRole('button', {name: 'Ripple delete', exact: true}).click();
  await expect(page.locator('.track.lyric .timeline-clip')).toHaveCount(1);
  await page.locator('.track.lyric .timeline-clip').click(); await expect(page.getByLabel('Line start (s)', {exact: true})).toHaveValue('5');
  await page.locator('.ruler').click({position: {x: 216, y: 10}});
  await page.getByRole('button', {name: 'Hide Lyrics', exact: true}).click();
  await expect(page.locator('[data-proof-frame]')).toHaveAttribute('data-line-id', '');
  await page.getByRole('button', {name: 'Hide Lyrics', exact: true}).click();
  await page.getByRole('button', {name: 'Save', exact: true}).click(); await page.getByRole('status').filter({hasText: /^Saved$/}).waitFor();
  assert.equal(JSON.parse(await readFile(file, 'utf8')).schemaVersion, 2);
  assert.equal(await readFile(`${file}.v1.bak`, 'utf8'), original);
  await page.reload(); await page.getByRole('button', {name: `${legacy.name} Open`, exact: true}).click();
  await expect(page.locator('.track.lyric .timeline-clip')).toHaveCount(1);
  await mkdir('artifacts/advanced', {recursive: true}); await page.screenshot({path: 'artifacts/advanced/tracks.png', fullPage: true});
  assert.deepEqual(errors, []);
  console.log('Unified timeline passed: V1 opening/backup, rectangle/group selection, batch movement, locks, clipboard, ripple, undo/redo, visibility, save/reopen.');
} finally {
  await browser.close(); await web.close(); await api.app.close();
  assert.equal(path.dirname(root), path.resolve(tmpdir())); assert(path.basename(root).startsWith('lyrics-track-browser-'));
  await rm(root, {recursive: true, force: true});
}
